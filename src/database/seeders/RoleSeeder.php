        $roles = [
            'admin',
            'petugas',
            'anggota',
            'kepala_perpustakaan',
        ];

        foreach ($roles as $role) {
            Role::firstOrCreate([
                'name' => $role,
                'guard_name' => 'web',
            ]);
        }
    }
}
